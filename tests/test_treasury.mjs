import assert from 'node:assert/strict';
import {assetValueUsd,totalUsd,decimal,quantity,money,assetValue,total,delta,recordChange,capture,previousSnapshot,canArchive,lastAssetChange} from '../static/treasury-model.js';
const asset=(id,category,price)=>({id,name:id,category,priceCny:price,unit:category==='crypto'?'BTC':'元',archived:false});
const account=(id,assetId,amount)=>({id,assetId,amount,name:id,archived:false});
const t={assets:[asset('btc','crypto','500000'),asset('cash','cash','1'),asset('risk','investment','1')],accounts:[account('a','btc','0.1'),account('b','btc','0.2'),account('c','cash','1000.13'),account('d','risk','2000')],changes:[],snapshots:[]};
assert.equal(quantity(assetValue(t,t.assets[0]).amount),'0.3');
assert.equal(money(total(t).value),'¥153,000.13');
assert.equal(money(total(t,'controlled').value),'¥151,000.13');
assert.equal(money(total(t,'investment').value),'¥2,000.00');
assert.equal(total(t).complete,true);
assert.equal(quantity(decimal('0.000000000001')),'0.000000000001');
for(const input of ['1e3','-1','NaN','1,000','0.0000000000001','9999999999999999'])assert.throws(()=>decimal(input));
assert.equal(money(decimal('1.005')),'¥1.01');
assert.equal(money(-decimal('0.015')),'−¥0.02');
capture(t,{id:'s1',date:'2026-09-30',label:'9月',note:'',createdAt:'2026-10-16T00:00:00Z'});
recordChange(t,p=>p.accounts[0].amount='0.15','增持','c1','now');
assert.equal(money(delta(t.changes[0].before,t)),'¥25,000.00');
assert.equal(t.snapshots[0].portfolio.accounts[0].amount,'0.1');
recordChange(t,p=>p.assets[0].priceCny='600000','改价','c2','now');
assert.equal(money(delta(t.changes[1].before,t)),'¥35,000.00');
assert.equal(t.snapshots[0].portfolio.assets[0].priceCny,'500000');
recordChange(t,p=>p.accounts[2].name='现金改名','改名','c3','now');assert.equal(lastAssetChange(t,'btc').id,'c2');
capture(t,{id:'s2',date:'2026-10-16',label:'10月',note:'',createdAt:'2026-10-16T01:00:00Z'});
assert.equal(previousSnapshot(t,'s2').id,'s1');
assert.equal(canArchive(t,'btc'),false);
t.accounts.push(account('empty','btc',null));assert.equal(total(t).complete,false);assert.equal(delta(t.changes[0].before,t),null);
t.accounts.at(-1).amount='0';assert.equal(total(t).complete,true);
t.assets[0].priceCny=null;assert.equal(assetValue(t,t.assets[0]).value,null);
for(const a of t.accounts.filter(a=>a.assetId==='btc'))a.amount='0';assert.equal(assetValue(t,t.assets[0]).value,0n);assert.equal(canArchive(t,'btc'),true);
assert.throws(()=>capture({assets:[],accounts:[],snapshots:[]},{id:'empty'}));
console.log('Treasury scenarios passed: decimal precision, wallet aggregation, external funds, missing vs zero, price changes, fixed snapshots, archive safeguards.');

const market={frequency:'daily',prices:{bitcoin:{usd:'100',at:'2026-10-16T08:00:00Z',source:'CoinGecko'}},fx:{USD:{rate:'7',date:'2026-10-16',source:'Frankfurter'}}};
const auto={assets:[{...asset('auto','crypto','500'),pricingMode:'auto',quoteId:'bitcoin'}],accounts:[account('auto1','auto','0.1'),account('auto2','auto','0.2')],market,changes:[],snapshots:[]};
assert.equal(money(total(auto).value),'¥210.00');
capture(auto,{id:'auto-snapshot',date:'2026-10-16',label:'market snapshot',createdAt:'2026-10-16T08:00:00Z',note:''});
recordChange(auto,p=>p.market.prices.bitcoin.usd='200','行情更新','market-change','2026-10-16T09:00:00Z');
assert.equal(money(total(auto).value),'¥420.00');
assert.equal(money(total(auto.snapshots[0].portfolio).value),'¥210.00');
assert.equal(lastAssetChange(auto,'auto').id,'market-change');
auto.assets[0].pricingMode='manual';assert.equal(money(total(auto).value),'¥150.00');
auto.assets[0].pricingMode='auto';delete auto.market.fx.USD;assert.equal(money(total(auto).value),'¥150.00');
auto.assets[0].priceCny=null;assert.equal(total(auto).complete,false);
auto.accounts.forEach(r=>r.amount='0');assert.equal(money(total(auto).value),'¥0.00');
console.log('Market scenarios passed: native USD conversion, multi-wallet totals, manual fallback, cached quotes, immutable historical FX and prices.');

const usdPortfolio={assets:[{...asset('eth','crypto','1400'),pricingMode:'auto',quoteId:'ethereum'},{...asset('usdc','crypto','7'),pricingMode:'auto',quoteId:'usd-coin'}],accounts:[account('w1','eth','0.1'),account('w2','eth','0.2'),account('w3','usdc','40')],market:{prices:{ethereum:{usd:'200'},'usd-coin':{usd:'1'}},fx:{USD:{rate:'7'}}}};
assert.equal(quantity(assetValueUsd(usdPortfolio,usdPortfolio.assets[0]).value),'60');
assert.equal(quantity(totalUsd(usdPortfolio).value),'100');
assert.equal(totalUsd(usdPortfolio).missing,0);
delete usdPortfolio.market.fx.USD;
assert.equal(quantity(totalUsd(usdPortfolio).value),'100'); // Native USD does not require FX.
usdPortfolio.assets[0].pricingMode='manual';
assert.equal(totalUsd(usdPortfolio).missing,1);assert.equal(quantity(totalUsd(usdPortfolio).value),'40');
usdPortfolio.market.fx.USD={rate:'7'};
assert.equal(quantity(totalUsd(usdPortfolio).value),'100');assert.equal(totalUsd(usdPortfolio).converted,true);
usdPortfolio.accounts[0].amount=null;
assert.equal(totalUsd(usdPortfolio).missing,1);assert.equal(quantity(totalUsd(usdPortfolio).value),'80');
usdPortfolio.assets[1].archived=true;
assert.equal(quantity(totalUsd(usdPortfolio).value),'40');
usdPortfolio.accounts[0].amount='0';usdPortfolio.accounts[1].amount='0';delete usdPortfolio.market.fx.USD;
assert.equal(totalUsd(usdPortfolio).value,0n);assert.equal(totalUsd(usdPortfolio).missing,0);
usdPortfolio.accounts=[];assert.equal(totalUsd(usdPortfolio).value,null);
assert.equal(totalUsd({assets:[],accounts:[]}).value,0n);
console.log('USD category display passed: holding values, wallet sum, independent native quote, explicit manual conversion, partial values and zero.');
