usdPortfolio.accounts=[];assert.equal(totalUsd(usdPortfolio).value,null);
assert.equal(totalUsd({assets:[],accounts:[]}).value,0n);
console.log('USD category display passed: holding values, wallet sum, independent native quote, explicit manual conversion, partial values and zero.');

const {adjustAccount,treasuryTrend,scopedValue}=await import('../static/treasury-model.js');
const movement={assets:[asset('fund','cash','1'),asset('coin','crypto','200')],accounts:[account('reserve','fund','100.10'),account('wallet','coin','0.1'),account('unknown','coin',null)],changes:[],snapshots:[]};
assert.equal(adjustAccount(movement,'reserve','add','0.20','2026-10-01T00:00:00Z').after,'100.3');
assert.equal(adjustAccount(movement,'reserve','subtract','0.1','2026-10-01T00:00:01Z').after,'100.2');
assert.throws(()=>adjustAccount(movement,'reserve','subtract','101','x'));
assert.throws(()=>adjustAccount(movement,'unknown','add','1','x'));
assert.throws(()=>adjustAccount(movement,'reserve','add','0','x'));
assert.throws(()=>adjustAccount(movement,'reserve','bogus','1','x'));
assert.equal(adjustAccount(movement,'wallet','add','0.000000000001','2026-10-01T00:00:02Z').after,'0.100000000001');
movement.accounts.find(a=>a.id==='unknown').amount='0';
capture(movement,{id:'past',date:'2026-09-30',createdAt:'2026-10-01T00:00:00Z',label:'过去盘点',note:''});
recordChange(movement,p=>adjustAccount(p,'reserve','add','50','2026-10-02T00:00:00Z'),'储备转入','up','2026-10-02T00:00:00Z');
recordChange(movement,p=>adjustAccount(p,'reserve','subtract','20','2026-10-03T00:00:00Z'),'储备取出','down','2026-10-03T00:00:00Z');
let line=treasuryTrend(movement,{kind:'account',id:'reserve'},{to:'2026-10-04T00:00:00Z'});
assert.equal(quantity(line[0].value),'100.2');assert.equal(quantity(line.at(-1).value),'130.2');
assert.equal(quantity(scopedValue(movement,{kind:'category',id:'cash'}).value),'130.2');
assert.equal(quantity(scopedValue(movement,{kind:'asset',id:'fund'}).value),'130.2');
assert.equal(line.find(p=>p.id==='past').at,'2026-09-30T12:00:00+08:00');
assert.equal(movement.snapshots[0].portfolio.accounts[0].amount,'100.2');
movement.accounts.find(r=>r.id==='reserve').amount=null;
line=treasuryTrend(movement,{kind:'account',id:'reserve'},{from:'2026-10-03T00:00:00Z',to:'2026-10-04T00:00:00Z'});
assert.equal(line.at(-1).value,null);assert.equal(line.some(p=>p.id==='up'),false);
assert.equal(scopedValue(movement,{kind:'total'}).value,null);
assert.equal(scopedValue(movement,{kind:'account',id:'absent'}).value,null);
assert.equal(scopedValue(movement,{kind:'account',id:'unknown'}).value,0n);
assert.equal(scopedValue(movement,{kind:'account',id:'wallet'}).value,decimal('20.0000000002'));
assert.equal(treasuryTrend(movement,{kind:'account',id:'reserve'},{to:'2026-10-02T12:00:00Z'}).some(p=>p.id==='down'),false);
console.log('Treasury changes/trends: exact additions/subtractions, unknown balances, overdraft guards, account/category scopes, dated snapshots, historical preservation and gaps passed.');
