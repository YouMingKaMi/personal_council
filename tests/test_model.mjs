const {configAt,metric,setNumber,toggleItem,addVersion,completeDay,chronicleComplete,moveEvent,monthDates}=await import('../static/tracking-model.js');
const v={id:'v1',fromDate:'2026-10-01',name:'饮食',kind:'checklist',items:[{id:'fruit',name:'水果'},{id:'nuts',name:'坚果'},{id:'oil',name:'鱼油'}],policy:'all',target:3,unit:'项',enabled:true,days:[0,1,2,3,4,5,6]};
const h={versions:[v],entries:{}};
for(const item of ['fruit','nuts','oil'])toggleItem(h,'2026-10-15',item,'now');
assert.equal(metric(h,'2026-10-15').done,true);
addVersion(h,{...v,id:'v2',fromDate:'2026-10-16',items:v.items.filter(i=>i.id!=='nuts'),target:2});
assert.equal(metric(h,'2026-10-15').total,3);
assert.equal(metric(h,'2026-10-16').total,2);
assert.equal(metric(h,'2026-10-16').recorded,false);
for(const item of ['fruit','oil'])toggleItem(h,'2026-10-16',item,'now');
assert.equal(metric(h,'2026-10-16').done,true);
assert.throws(()=>toggleItem(h,'2026-10-16','nuts','now'));
assert.throws(()=>addVersion(h,{...v,id:'bad',fromDate:'2026-10-16'}));
assert.equal(configAt(h,'2026-09-30'),null);
const numeric={versions:[{...v,id:'num',kind:'number',target:2.5}],entries:{}};
setNumber(numeric,'2026-10-15',0,'now');assert.equal(metric(numeric,'2026-10-15').recorded,true);
setNumber(numeric,'2026-10-15',2.5,'now');assert.equal(metric(numeric,'2026-10-15').done,true);
assert.throws(()=>setNumber(numeric,'2026-10-15',NaN,'now'));
